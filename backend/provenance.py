"""Provenance for generated documents — a sidecar that makes drift detectable.

`marketing/cost-one-pager.html` leaves the building. It is regenerated by
`python -m scripts.cost_onepager`, and until now nothing noticed if someone
edited the committed file, or if a change to the renderer (a column, a
rounding rule, the wording of a caveat) left the committed page describing
an older pipeline. The document would simply become a little bit wrong,
which is the worst failure mode for a document that makes cost claims.

So every generated artifact gets a `<name>.source.json` next to it:

- the exact `CostComparisonRequest` inputs it was rendered from,
- the ledger figures the comparison actually used (a small excerpt: the
  fields `compare_costs` reads, nothing else — no ticket bodies, no email
  addresses, no ids),
- the declared sha256 of the HTML,
- a manifest version, so a format change is loud instead of silent.

`verify` answers two questions offline, with no ledger, no server and no
network: *is this the file that was signed for?* (digest) and *does the
current renderer still produce this file from these inputs?* (re-render).
Anything a browser would print is reproducible from the sidecar alone.

This is the cheap half of the idea behind signed decision receipts: pin
what went in, then let the artifact prove it still says the same thing.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any

from .cost_compare import compare_costs
from .models import CostComparison, CostComparisonRequest
from .one_pager import render_one_pager

MANIFEST_VERSION = 1

# The only run fields `compare_costs` reads. Keeping the excerpt to these is
# what makes it safe to commit: costs and outcomes, never customer data.
LEDGER_FIELDS = ("disposition", "total_cost_usd")

REQUEST_FIELDS = ("monthly_volume", "resolution_rate_pct", "seats", "plan_slugs",
                  "per_outcome_usd", "seat_price_usd", "flat_monthly_usd",
                  "platform_monthly_usd", "include_human_review_cost",
                  "human_hourly_rate_usd", "human_minutes_per_escalation")


def sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def ledger_excerpt(runs: list[dict]) -> list[dict]:
    """The cost-relevant slice of the run ledger: outcome and price."""
    return [{k: r.get(k) for k in LEDGER_FIELDS} for r in runs]


def request_dict(req: CostComparisonRequest) -> dict[str, Any]:
    """The effective inputs, defaults included.

    Not "only what was overridden": a reader of the sidecar must be able to
    see that the page claims 1,500 conversations a month, whether the person
    who ran the generator typed that number or accepted the default.
    """
    return {k: getattr(req, k) for k in REQUEST_FIELDS}


def build_source(comparison: CostComparison, html: str, req: CostComparisonRequest,
                 runs: list[dict], *, artifact_name: str,
                 render_options: dict[str, Any] | None = None) -> dict:
    """The sidecar document for one rendered artifact."""
    return {
        "manifest_version": MANIFEST_VERSION,
        "generated_by": "scripts.cost_onepager",
        "artifact": artifact_name,
        "artifact_sha256": sha256_text(html),
        "renderer": {
            "module": "backend.one_pager",
            "function": "render_one_pager",
            "options": render_options or {},
        },
        "request": request_dict(req),
        "ledger": {
            "decisions": comparison.measured_from_decisions,
            "cost_per_decision_usd": comparison.measured_cost_per_decision_usd,
            "measurement_basis": comparison.measurement_basis,
            "escalations_per_month": comparison.escalations_per_month,
            "mode": comparison.mode,
        },
        "ledger_excerpt": ledger_excerpt(runs),
    }


def source_path_for(artifact: Path) -> Path:
    return artifact.with_suffix(".source.json")


def write_artifact(artifact: Path, html: str, req: CostComparisonRequest,
                   runs: list[dict], *, render_options: dict[str, Any] | None = None) -> Path:
    """Write the HTML and its sidecar together, so they cannot disagree."""
    artifact.parent.mkdir(parents=True, exist_ok=True)
    artifact.write_text(html, encoding="utf-8")
    comparison = compare_costs(runs, req)
    source = build_source(comparison, html, req, runs,
                          artifact_name=artifact.name,
                          render_options=render_options)
    sidecar = source_path_for(artifact)
    sidecar.write_text(json.dumps(source, indent=1, ensure_ascii=False) + "\n",
                       encoding="utf-8")
    return sidecar


def rebuild(source: dict) -> str:
    """Render the HTML the sidecar describes, with the current renderer."""
    req = CostComparisonRequest(**source.get("request", {}))
    options = (source.get("renderer") or {}).get("options") or {}
    return render_one_pager(compare_costs(source.get("ledger_excerpt", []), req), **options)


def verify(artifact: Path) -> dict:
    """Check the committed artifact against its sidecar and the renderer.

    Returns {"ok": bool, "reason": str, "checked": {...}} — never raises for a
    mismatch, because the caller wants to print why it failed, not a traceback.
    """
    sidecar = source_path_for(artifact)
    if not artifact.exists():
        return {"ok": False, "reason": f"artifact missing: {artifact.name}"}
    if not sidecar.exists():
        return {"ok": False, "reason": f"provenance sidecar missing: {sidecar.name}"}

    try:
        source = json.loads(sidecar.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        return {"ok": False, "reason": f"sidecar is not valid JSON: {exc}"}

    version = source.get("manifest_version")
    if version != MANIFEST_VERSION:
        return {"ok": False,
                "reason": f"sidecar manifest_version {version!r} != {MANIFEST_VERSION}"}

    html = artifact.read_text(encoding="utf-8")
    actual = sha256_text(html)
    declared = source.get("artifact_sha256")
    if actual != declared:
        return {"ok": False,
                "reason": (f"{artifact.name} digest {actual[:12]}… does not match the "
                           f"sidecar's {str(declared)[:12]}… — the file was edited or "
                           f"replaced after generation"),
                "checked": {"sha256": actual}}

    try:
        expected = rebuild(source)
    except Exception as exc:  # a sidecar that no longer fits the model is drift too
        return {"ok": False, "reason": f"re-render failed: {type(exc).__name__}: {exc}"}

    if expected != html:
        return {"ok": False,
                "reason": ("the current renderer produces different HTML from the same "
                           "inputs — regenerate with `python -m scripts.cost_onepager`"),
                "checked": {"expected_sha256": sha256_text(expected), "actual_sha256": actual}}

    ledger = source.get("ledger", {})
    return {
        "ok": True,
        "reason": "artifact matches its provenance and the current renderer",
        "checked": {
            "sha256": actual,
            "decisions": ledger.get("decisions"),
            "measurement_basis": ledger.get("measurement_basis"),
            "cost_per_decision_usd": ledger.get("cost_per_decision_usd"),
        },
    }
